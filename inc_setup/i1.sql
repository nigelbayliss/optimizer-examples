-- Create range-partitioned table with a virtual column for natural log
CREATE TABLE sales_data
(
  id            NUMBER GENERATED BY DEFAULT AS IDENTITY,
  txn_date      DATE       NOT NULL,
  amount        NUMBER     NOT NULL,
  amount_ln     GENERATED ALWAYS AS (LN(NULLIF(amount, 0))) VIRTUAL, -- avoid ln(0)
  description   VARCHAR2(100)
)
PARTITION BY RANGE (txn_date)
(
  PARTITION p2020 VALUES LESS THAN (DATE '2021-01-01'),
  PARTITION p2021 VALUES LESS THAN (DATE '2022-01-01'),
  PARTITION p2022 VALUES LESS THAN (DATE '2023-01-01'),
  PARTITION p2023 VALUES LESS THAN (DATE '2024-01-01'),
  PARTITION p2024 VALUES LESS THAN (DATE '2025-01-01')
); 

-- Helper: function to generate a date within a given year uniformly
-- (Optional: you can inline logic in inserts; this keeps it readable)
CREATE OR REPLACE FUNCTION rand_date_in_year(p_year IN PLS_INTEGER)
RETURN DATE DETERMINISTIC
AS
  v_start DATE := TO_DATE(p_year || '-01-01','YYYY-MM-DD');
  v_days  PLS_INTEGER := ADD_MONTHS(v_start, 12) - v_start; -- 365 or 366
BEGIN
  RETURN v_start + TRUNC(DBMS_RANDOM.VALUE(0, v_days));
END;
/ 

-- Seed the random generator (optional)
BEGIN
  DBMS_RANDOM.SEED(TO_NUMBER(TO_CHAR(SYSTIMESTAMP,'FF')));
END;
/ 

